#!/usr/bin/env python3
"""Generate a report.md + response plot(s) from recorder output.

Takes one or more directories written by `confirm_point.py`/`psweep_tune.py`'s
`--record-dir` (each holding `monitor.csv`, `events.jsonl`, `summary.json` from
`scorecard_core.Recorder`) and writes a standardized `report.md` + plot next to
them. This replaces hand-writing bench-results narration: run a real session,
then run this against its recorder directory, don't write report.md by hand.

Usage:
    bench_report.py captures/20261105T120000.000000Z --out docs/bench-results/my-run
    bench_report.py captures/run1 captures/run2 --out docs/bench-results/ab-compare --title "A/B compare"
"""
import argparse
import csv
import json
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt


def read_run(run_dir):
    run_dir = Path(run_dir)
    rows = []
    with (run_dir / 'monitor.csv').open(newline='') as f:
        for row in csv.DictReader(f):
            rows.append({k: int(v) for k, v in row.items()})
    events = []
    events_path = run_dir / 'events.jsonl'
    if events_path.exists():
        events = [json.loads(line) for line in events_path.open() if line.strip()]
    summary = {}
    summary_path = run_dir / 'summary.json'
    if summary_path.exists():
        summary = json.loads(summary_path.read_text())
    return dict(dir=run_dir, rows=rows, events=events, summary=summary)


def find_event(run, kind):
    for e in run['events']:
        if e.get('kind') == kind:
            return e
    return None


def plot_run(run, out_path):
    rows = run['rows']
    if not rows:
        return False
    ticks = list(range(len(rows)))
    fig, axes = plt.subplots(3, 1, sharex=True, figsize=(8, 6))
    axes[0].plot(ticks, [r['position'] for r in rows])
    axes[0].set_ylabel('position (ct)')
    axes[1].plot(ticks, [r['velocity'] for r in rows])
    axes[1].set_ylabel('velocity (ct/tick)')
    axes[2].plot(ticks, [r['physical_torque'] for r in rows])
    axes[2].set_ylabel('torque (raw)')
    axes[2].set_xlabel('tick')
    fig.tight_layout()
    fig.savefig(out_path)
    plt.close(fig)
    return True


def run_section(run, index, multi):
    lines = [f"## Run: `{run['dir'].name}`", '']
    info = find_event(run, 'session')
    if info:
        fields = ', '.join(f'{k}={v}' for k, v in info.items() if k not in ('kind', 'utc', 'monotonic'))
        lines += [f'Session: {fields}', '']
    summary = find_event(run, 'confirm_summary') or (run['summary'] if run['summary'] else None)
    if summary:
        settles = summary.get('settles') or []
        overshoots = summary.get('overshoots') or []
        fails = summary.get('fails', 0)
        if settles:
            lines.append(f'Settle: mean {sum(settles) / len(settles):.0f} ms, '
                          f'min {min(settles):.0f}, max {max(settles):.0f} '
                          f'({len(settles)} trial(s))')
        if overshoots:
            lines.append(f'Overshoot: mean {sum(overshoots) / len(overshoots):.1f} ct, '
                          f'min {min(overshoots)}, max {max(overshoots)}')
        if fails:
            lines.append(f'{fails} trial(s) failed to settle/guard-stopped.')
        if settles or overshoots or fails:
            lines.append('')
    plot_name = f'response-{index}.png' if multi else 'response.png'
    lines += [f'![response]({plot_name})', '']
    return lines, plot_name


def write_report(runs, out_dir, title):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    lines = [f'# {title}', '',
             'Generated by `tools/bench_report.py` from recorder output '
             '(`confirm_point.py`/`psweep_tune.py` `--record-dir`) -- not hand-written. '
             'Re-run the script against fresh captures rather than editing this file by hand.',
             '']
    multi = len(runs) > 1
    for i, run in enumerate(runs):
        section, plot_name = run_section(run, i, multi)
        plot_run(run, out_dir / plot_name)
        lines += section
    (out_dir / 'report.md').write_text('\n'.join(lines) + '\n')


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('run_dirs', nargs='+', help='One or more recorder directories')
    p.add_argument('--out', required=True, help='Output directory for report.md + plot(s)')
    p.add_argument('--title', default='Bench run')
    args = p.parse_args(argv)
    runs = [read_run(d) for d in args.run_dirs]
    write_report(runs, args.out, args.title)
    print(f'Wrote {args.out}/report.md')


if __name__ == '__main__':
    main()
